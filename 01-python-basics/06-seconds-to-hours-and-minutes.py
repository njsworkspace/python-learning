"""
แบบฝึกหัด: แปลงวินาทีเป็นชั่วโมงและนาที
จุดประสงค์: ฝึกใช้การหารเอาส่วน (//) และการหารเอาเศษ (%)
โปรแกรมแสดงจำนวนชั่วโมงเต็มและนาทีที่เหลือจากจำนวนวินาทีที่กรอก
"""

# รับจำนวนวินาทีและแปลงเป็นจำนวนเต็ม
seconds = int(input("Enter the number of seconds: "))

# หาจำนวนชั่วโมงเต็มด้วยการหารเอาส่วนด้วย 3,600 วินาที
hours = seconds // 3600
# หาเศษวินาทีหลังตัดชั่วโมงออก แล้วหารเอาส่วนเพื่อแปลงเป็นนาทีเต็ม
minutes = (seconds % 3600) // 60


# แสดงเวลาที่แปลงได้เป็นชั่วโมงและนาที
print(f"{seconds} seconds is equal to {hours} hours and {minutes} minutes.")