def sum_array(a):
    # ถ้าลิสต์มีสมาชิก ให้หาผลรวมของตัวเลขทั้งหมด
    if a:
        return sum(a)

    # ถ้าลิสต์ว่าง ให้คืนค่า 0
    return 0


a = [1, 5.2, 4, 0, -1]
print(sum_array(a))