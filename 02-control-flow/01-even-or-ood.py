"""
แบบฝึกหัด: ตรวจสอบเลขคู่หรือเลขคี่
จุดประสงค์: ฝึกใช้ if-else และตัวดำเนินการหารเอาเศษ (%)
ถ้าหารจำนวนเต็มด้วย 2 แล้วเหลือเศษ 0 จะแสดงว่าเป็นเลขคู่ มิฉะนั้นเป็นเลขคี่
"""

# รับตัวเลขจากผู้ใช้และแปลงเป็นจำนวนเต็ม
number = int(input("กรอกตัวเลข: "))

# ตรวจสอบว่าเมื่อนำตัวเลขหาร 2 แล้วไม่เหลือเศษหรือไม่
if number % 2 == 0:
    # กรณีเศษเป็น 0 แสดงว่าเป็นเลขคู่
    print('Even')
else:
    # กรณีอื่นเป็นเลขคี่
    print('Odd')