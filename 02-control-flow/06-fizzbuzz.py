
"""
แบบฝึกหัด: FizzBuzz ตั้งแต่ 1 ถึง 30
จุดประสงค์: ฝึกใช้ for loop เงื่อนไขหลายกรณี และหารเอาเศษ (%)
จำนวนที่หาร 3 ลงตัวแสดง Fizz, หาร 5 ลงตัวแสดง Buzz,
หารทั้ง 3 และ 5 ลงตัวแสดง FizzBuzz และกรณีอื่นแสดงตัวเลข
"""

# วนตรวจตัวเลขตั้งแต่ 1 ถึง 30 รวมเลข 30
for i in range(1, 31):
    # เก็บเศษจากการหารด้วย 3 เพื่อเช็กว่าเป็นพหุคูณของ 3 หรือไม่
    remainder_3 = i % 3
    # เก็บเศษจากการหารด้วย 5 เพื่อเช็กว่าเป็นพหุคูณของ 5 หรือไม่
    remainder_5 = i % 5

    # ตรวจกรณีหารลงตัวทั้ง 3 และ 5 ก่อนกรณีใดกรณีหนึ่ง
    if remainder_3 == 0 and remainder_5 == 0:
        # แสดง FizzBuzz เมื่อเป็นพหุคูณของทั้งสองจำนวน
        print('FizzBuzz')
    # ตรวจกรณีที่หาร 3 ลงตัว
    elif remainder_3 == 0:
        # แสดง Fizz เมื่อเป็นพหุคูณของ 3
        print('Fizz')
    # ตรวจกรณีที่หาร 5 ลงตัว
    elif remainder_5 == 0:
        # แสดง Buzz เมื่อเป็นพหุคูณของ 5
        print('Buzz')
    else:
        # แสดงตัวเลขเดิมเมื่อไม่เข้าเงื่อนไขข้างต้น
        print(i)