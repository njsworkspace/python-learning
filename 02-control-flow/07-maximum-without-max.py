# สร้างลิสต์ตัวเลขตัวอย่างเพื่อค้นหาค่าสูงสุด
numbers = [1, 2, 3, 4, 5]
# ตรวจว่าลิสต์ไม่มีสมาชิกหรือไม่
if not numbers:
    # กำหนดข้อความแทนค่าสูงสุดเมื่อไม่มีข้อมูลให้เปรียบเทียบ
    highest = "List is empty"
else:
    # ใช้สมาชิกตัวแรกเป็นค่าสูงสุดชั่วคราวสำหรับเริ่มเปรียบเทียบ
    highest = numbers[0]

# วนตรวจสมาชิกทุกตัวในลิสต์
for number in numbers:
    # เปรียบเทียบสมาชิกปัจจุบันกับค่าสูงสุดที่เก็บไว้
    if number > highest:
        # อัปเดตค่าสูงสุดเมื่อพบสมาชิกที่มากกว่า
        highest = number


# แสดงค่าสูงสุดที่หาได้
print(f"Maximum value: {highest}")