# รับคะแนนจากผู้ใช้และแปลงเป็นจำนวนเต็ม
score = int(input("Enter Score: "))

# แสดงคะแนนที่กรอกไว้เพื่อให้เห็นข้อมูลก่อนแปลผล
print(f"Score: {score}")

# ตรวจสอบคะแนนที่อยู่นอกช่วง 0 ถึง 100 ก่อนเงื่อนไขเกรด
if score > 100 or score < 0:
    # แจ้งว่าคะแนนไม่ถูกต้องเมื่อเกิน 100 หรือต่ำกว่า 0
    print('Invalid score')
# ถ้าคะแนนไม่ผิดช่วง ให้ตรวจเกณฑ์จากคะแนนสูงลงมาต่ำ
elif score >= 80:
    # คะแนนตั้งแต่ 80 ขึ้นไปได้เกรด A
    print('Grade: A')
elif score >= 70:
    # คะแนนตั้งแต่ 70 แต่ไม่ถึง 80 ได้เกรด B
    print('Grade: B')
elif score >= 60:
    # คะแนนตั้งแต่ 60 แต่ไม่ถึง 70 ได้เกรด C
    print('Grade: C')
elif score >= 50:
    # คะแนนตั้งแต่ 50 แต่ไม่ถึง 60 ได้เกรด D
    print('Grade: D')
else:
    # คะแนนที่เหลือในช่วง 0 ถึง 49 ได้เกรด F
    print('Grade: F')
