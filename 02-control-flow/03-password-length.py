# รับรหัสผ่านที่ผู้ใช้ตั้งเป็นข้อความ
password = input("กรุณาตั้ง Password:")

# นับจำนวนตัวอักษรในรหัสผ่านเพื่อใช้ตรวจระดับความยาว
count_characters = len(password)

# ใส่เงื่อนไข
# ตรวจว่ารหัสผ่านมีความยาวน้อยกว่า 8 ตัวหรือไม่
if count_characters < 8:
    # แสดงคำเตือนเมื่อรหัสผ่านสั้นเกินไป
    print('Too short')
# ตรวจช่วง 8 ถึง 11 ตัว (กรณีสั้นกว่านั้นถูกกรองไปแล้ว)
elif count_characters <= 11:
    # แสดงระดับความยาวที่พอใช้
    print('Acceptable length')
else:
    # กรณีที่เหลือยาวกว่า 11 ตัว
    print('Good length')