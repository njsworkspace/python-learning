"""
แบบฝึกหัด: แสดงสูตรคูณ
จุดประสงค์: ฝึกใช้ for loop และ range() ทำซ้ำตามจำนวนรอบที่กำหนด
โปรแกรมแสดงสูตรคูณของตัวเลขที่กรอก ตั้งแต่แม่ 1 ถึงแม่ 12
"""

# Input
# รับแม่สูตรคูณจากผู้ใช้และแปลงเป็นจำนวนเต็ม
number = int(input("Enter number: "))

# Process & Output
# วนค่า i ตั้งแต่ 1 ถึง 12 เพื่อสร้างสูตรคูณ 12 บรรทัด
for i in range(1, 13):
    # คูณแม่สูตรคูณกับลำดับรอบปัจจุบันแล้วแสดงผล
    print(f"{number} × {i} = {number * i}")