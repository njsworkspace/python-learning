"""
แบบฝึกหัด: หาผลรวมของจำนวนตั้งแต่ 1 ถึง n
จุดประสงค์: ฝึกใช้ for loop และสะสมผลลัพธ์ในตัวแปร total
โปรแกรมบวกตัวเลขทีละจำนวนและแสดงผลรวมสะสมในแต่ละรอบ
"""

# รับจำนวนปลายทาง n จากผู้ใช้
number = int(input("Enter number: "))

# แสดงค่าที่ผู้ใช้ป้อนเพื่อยืนยันข้อมูล
print(f"Enter number: {number}")

# ตั้งผลรวมเริ่มต้นเป็นศูนย์ก่อนเริ่มบวก
total = 0
# คำนวณผลรวมโดยใช้ลูป
# วนตัวเลขตั้งแต่ 1 จนถึง number รวมด้วย
for i in range(1, number + 1):
    # เพิ่มค่ารอบปัจจุบันเข้าไปในผลรวมสะสม
    total += i
    # แสดงผลรวมสะสมของรอบนี้
    print(f"Total: {total}")